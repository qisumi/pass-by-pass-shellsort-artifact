def check_worked_example():
    print("\n=== Worked example (n=36, h_j=6) ===")
    H = [32, 27, 24, 18, 16, 12, 9, 8, 6]
    j = H.index(6) + 1
    reach = semigroup_below(H[: j - 1], 36)
    Q = [m for m in range(0, 6) if 6 * m in reach]
    G = [m for m in range(1, 6) if m not in Q]
    # lambda_j: 6 = 18 - 12
    lam = 2 if 18 in H[: j - 1] and 12 in H[: j - 1] else None
    ok = (2 in Q and 3 in Q and G == [1] and lam == 2)
    print(f"  Q_6 contains 2,3: {2 in Q and 3 in Q}; missing multipliers: {G} "
          f"(genus {len(G)} < LB=3); lambda_j={lam}")
    print(f"  {'OK' if ok else 'MISMATCH'}")
    return ok


